# Public API
# ---------------------------------------------------------------------------

def parse(pdf_path: str) -> dict:
    with pdfplumber.open(pdf_path) as pdf:
        if len(pdf.pages) != 1:
            raise ParserLayoutError(
                f"expected a single-page invoice (induction set was all single-page), "
                f"found {len(pdf.pages)} pages"
            )
        text = pdf.pages[0].extract_text()

    if not text:
        raise ParserLayoutError("no extractable text layer on page 1")

    lines = text.splitlines()

    def line_at(i, label):
        if i >= len(lines):
            raise ParserLayoutError(f"document ended before expected {label}")
        return lines[i]

    idx = 0

    supplier_name = line_at(idx, "supplier name line").strip()
    if not supplier_name:
        raise ParserLayoutError("empty supplier name line")
    idx += 1

    m = _match(_RECHNUNG_NR_RE, line_at(idx, "'Rechnung-Nr.' line"), "'Rechnung-Nr.' line")
    invoice_number = m.group(1)
    idx += 1

    m = _match(
        _STREET_DATE_RE,
        line_at(idx, "supplier street / Rechnungsdatum line"),
        "supplier street / Rechnungsdatum line",
    )
    supplier_street = m.group(1)
    issue_date = _date_to_iso(m.group(2), "Rechnungsdatum")
    idx += 1

    m = _match(
        _CITY_DATE_RE,
        line_at(idx, "supplier postcode/city/country / Leistungsdatum line"),
        "supplier postcode/city/country / Leistungsdatum line",
    )
    supplier_postcode, supplier_city, supplier_country_name = m.group(1), m.group(2), m.group(3)
    supply_date = _date_to_iso(m.group(4), "Leistungsdatum")
    supplier_country = _country_to_iso(supplier_country_name, "supplier country")
    idx += 1

    m = _match(
        _HRB_RE,
        line_at(idx, "'HRB ..., Amtsgericht ...' line"),
        "'HRB ..., Amtsgericht ...' line",
    )
    supplier_business_id = f"HRB {m.group(1)}"
    idx += 1

    m = _match(
        _FAELLIG_RE,
        line_at(idx, "'Fälligkeitsdatum' line"),
        "'Fälligkeitsdatum' line",
    )
    due_date = _date_to_iso(m.group(1), "Fälligkeitsdatum")
    idx += 1

    m = _match(
        _SUPPLIER_VAT_RE,
        line_at(idx, "supplier 'USt-IdNr.' line"),
        "supplier 'USt-IdNr.' line",
    )
    supplier_vat_id = m.group(1)
    idx += 1

    m = _match(_BESTELLNR_RE, line_at(idx, "'Bestellnummer' line"), "'Bestellnummer' line")
    po_number = m.group(1)
    idx += 1

    kaeufer_line = line_at(idx, "'KÄUFER' line").strip()
    if kaeufer_line != _KAEUFER_LABEL:
        raise ParserLayoutError(f"expected {_KAEUFER_LABEL!r} line, got: {kaeufer_line!r}")
    idx += 1

    buyer_name = line_at(idx, "buyer name line").strip()
    if not buyer_name:
        raise ParserLayoutError("empty buyer name line")
    idx += 1

    buyer_street = line_at(idx, "buyer street line").strip()
    if not buyer_street:
        raise ParserLayoutError("empty buyer street line")
    idx += 1

    m = _match(
        _BUYER_CITY_RE,
        line_at(idx, "buyer postcode/city/country line"),
        "buyer postcode/city/country line",
    )
    buyer_postcode, buyer_city, buyer_country_name = m.group(1), m.group(2), m.group(3)
    buyer_country = _country_to_iso(buyer_country_name, "buyer country")
    idx += 1

    m = _match(
        _REGISTERNUMMER_RE,
        line_at(idx, "'Registernummer:' line"),
        "'Registernummer:' line",
    )
    buyer_business_id = m.group(1)
    idx += 1

    m = _match(
        _BUYER_VAT_RE,
        line_at(idx, "buyer 'USt-IdNr.:' line"),
        "buyer 'USt-IdNr.:' line",
    )
    buyer_vat_id = m.group(1)
    idx += 1

    header_row = line_at(idx, "line-item table header").strip()
    if header_row != _HEADER_ROW:
        raise ParserLayoutError(f"expected table header {_HEADER_ROW!r}, got: {header_row!r}")
    idx += 1

    item_lines = []
    while True:
        raw = line_at(idx, "line item or 'Netto' totals line")
        if raw.startswith("Netto"):
            break
        item_lines.append(_parse_item_line(raw, idx + 1))
        idx += 1

    if not item_lines:
        raise ParserLayoutError("no line items found before 'Netto' line")

    m = _match(_NETTO_RE, line_at(idx, "'Netto' totals line"), "'Netto' totals line")
    net_canonical = _amount_to_canonical(m.group(1), "Netto amount")
    currency = _currency_to_iso(m.group(2), "Netto line currency symbol")
    idx += 1

    m = _match(_UST_RE, line_at(idx, "'Umsatzsteuer' totals line"), "'Umsatzsteuer' totals line")
    vat_rate_canonical = _rate_token_to_canonical(m.group(1), "Umsatzsteuer rate")
    vat_amount_canonical = _amount_to_canonical(m.group(2), "Umsatzsteuer amount")
    ust_currency = _currency_to_iso(m.group(3), "Umsatzsteuer line currency symbol")
    if ust_currency != currency:
        raise ParserLayoutError(
            f"Umsatzsteuer line currency {ust_currency!r} does not match Netto line currency {currency!r}"
        )
    idx += 1

    m = _match(_BRUTTO_RE, line_at(idx, "'Brutto' totals line"), "'Brutto' totals line")
    gross_canonical = _amount_to_canonical(m.group(1), "Brutto amount")
    brutto_currency = _currency_to_iso(m.group(2), "Brutto line currency symbol")
    if brutto_currency != currency:
        raise ParserLayoutError(
            f"Brutto line currency {brutto_currency!r} does not match Netto line currency {currency!r}"
        )
    idx += 1

    reverse_charge_line = line_at(idx, "reverse-charge mention line").strip()
    if reverse_charge_line != _REVERSE_CHARGE_TEXT:
        raise ParserLayoutError(
            f"expected reverse-charge mention {_REVERSE_CHARGE_TEXT!r}, got: {reverse_charge_line!r}"
        )
    idx += 1

    bank_label = line_at(idx, "'Bankverbindung' line").strip()
    if bank_label != _BANK_LABEL:
        raise ParserLayoutError(f"expected {_BANK_LABEL!r} line, got: {bank_label!r}")
    idx += 1

    m = _match(
        _IBAN_BIC_RE,
        line_at(idx, "'IBAN: ... BIC: ...' line"),
        "'IBAN: ... BIC: ...' line",
    )
    iban, bic = m.group(1), m.group(2)
    idx += 1

    m = _match(
        _ZAHLUNGSBED_RE,
        line_at(idx, "'Zahlungsbedingungen:' line"),
        "'Zahlungsbedingungen:' line",
    )
    payment_terms = m.group(1)
    idx += 1

    m = _match(
        _VERWENDUNGSZWECK_RE,
        line_at(idx, "'Verwendungszweck:' line"),
        "'Verwendungszweck:' line",
    )
    verwendungszweck = m.group(1)
    idx += 1

    if verwendungszweck != invoice_number:
        raise ParserLayoutError(
            f"'Verwendungszweck:' value {verwendungszweck!r} does not match "
            f"invoice number {invoice_number!r} -- this parser assumes it is always "
            f"a restatement of the invoice number, never a structured reference"
        )

    if idx != len(lines):
        raise ParserLayoutError(
            f"unexpected trailing content after 'Verwendungszweck:' line: {lines[idx:]!r}"
        )

    # ---- arithmetic reconciliation -----------------------------------
    net_dec = Decimal(net_canonical)
    vat_dec = Decimal(vat_amount_canonical)
    gross_dec = Decimal(gross_canonical)

    lines_sum = sum((Decimal(li["line_total"]) for li in item_lines), Decimal("0.00"))
    if lines_sum != net_dec:
        raise ParserLayoutError(f"line totals sum to {lines_sum} but printed Netto is {net_dec}")

    distinct_rates = {li["vat_rate"] for li in item_lines}
    if distinct_rates != {vat_rate_canonical}:
        raise ParserLayoutError(
            f"line item VAT rate(s) {sorted(distinct_rates)} do not match the single "
            f"Umsatzsteuer rate {vat_rate_canonical!r} (this parser only supports a "
            f"single VAT rate group, the only pattern observed for this supplier)"
        )

    expected_vat = (net_dec * Decimal(vat_rate_canonical) / Decimal("100")).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_UP
    )
    if expected_vat != vat_dec:
        raise ParserLayoutError(
            f"expected VAT amount {expected_vat} from rate {vat_rate_canonical}, printed {vat_dec}"
        )

    if net_dec + vat_dec != gross_dec:
        raise ParserLayoutError(f"Netto {net_dec} + Umsatzsteuer {vat_dec} != Brutto {gross_dec}")

    doc_id = Path(pdf_path).stem

    return {
        "schema_version": "1.0",
        "doc_id": doc_id,
        "supplier": {
            "name": supplier_name,
            "street": supplier_street,
            "postcode": supplier_postcode,
            "city": supplier_city,
            "country": supplier_country,
            "vat_id": supplier_vat_id,
            "business_id": supplier_business_id,
        },
        "buyer": {
            "name": buyer_name,
            "street": buyer_street,
            "postcode": buyer_postcode,
            "city": buyer_city,
            "country": buyer_country,
            "vat_id": buyer_vat_id,
            "business_id": buyer_business_id,
        },
        "invoice": {
            "number": invoice_number,
            "type": "invoice",
            "issue_date": issue_date,
            "supply_date": supply_date,
            "due_date": due_date,
            "payment_terms": payment_terms,
            "currency": currency,
            "po_number": po_number,
            "reference_type": None,
            "reference_value": None,
            "original_invoice_number": None,
            "reverse_charge_mention": reverse_charge_line,
        },
        "bank": {
            "iban": iban,
            "bic": bic,
            "bankgiro": None,
        },
        "lines": item_lines,
        "vat_summary": [
            {"rate": vat_rate_canonical, "base": net_canonical, "amount": vat_amount_canonical}
        ],
        "totals": {
            "net": net_canonical,
            "vat": vat_amount_canonical,
            "gross": gross_canonical,
        },
    }



"""
Deterministic parser for supplier s3 -- Falkenrath Beschlaege GmbH.

Machine-generated by the overseer agent (model: Claude Sonnet 5) on 2026-07-03.
Induced from 6 accepted LLM parses and their underlying PDFs / pdfplumber text
and word-coordinate dumps (no other files were consulted). Induction doc_ids:
  2025-01_s3_01, 2025-01_s3_02, 2025-02_s3_01,
  2025-02_s3_02, 2025-03_s3_01, 2025-03_s3_02

LAYOUT INDUCED (single-page German "Rechnung", read via pdfplumber
page.extract_text().splitlines() -- consistent across all 6 documents, only
the number of line-item rows varies):

  line  1      : supplier name (verbatim)
  line  2      : "Rechnung-Nr. <invoice number>"
  line  3      : "<supplier street> Rechnungsdatum <DD.MM.YYYY>"
  line  4      : "<plz> <city>, <country name> Leistungsdatum <DD.MM.YYYY>"
  line  5      : "HRB <digits>, Amtsgericht <court city>"   (court city is
                  context only -- business_id is "HRB <digits>")
  line  6      : "Faelligkeitsdatum <DD.MM.YYYY>"
  line  7      : "USt-IdNr. <supplier vat id>"               (no colon)
  line  8      : "Bestellnummer <po number>"
  line  9      : "KAEUFER"
  line 10      : buyer name (verbatim)
  line 11      : buyer street (verbatim)
  line 12      : "<plz> <city>, <country name>"
  line 13      : "Registernummer: <buyer business id>"
  line 14      : "USt-IdNr.: <buyer vat id>"                  (with colon)
  line 15      : "BEZEICHNUNG MENGE EINHEIT EINZELPREIS UST % GESAMT"
  line 16..N   : one row per line item:
                 "<description tokens...> <qty> ST <unit price> <vat%> <line total>"
                 (unit is always literally "ST" in the induction set; this is
                 used as the anchor token to split description from quantity)
  then         : "Netto <amount> <currency symbol>"
                 "Umsatzsteuer <rate digits> % <amount> <currency symbol>"
                 "Brutto <amount> <currency symbol>"
                 "Steuerfreie innergemeinschaftliche Lieferung"
                 "Bankverbindung"
                 "IBAN: <iban> BIC: <bic>"
                 "Zahlungsbedingungen: <payment terms>"
                 "Verwendungszweck: <invoice number restated>"

Notes on schema mapping, taken from the accepted parses:
  - Only VAT rate observed for this supplier is 0% (intra-EU reverse charge /
    exempt supply -- "Steuerfreie innergemeinschaftliche Lieferung" is always
    present). Rate token "0" maps to canonical vat_rate "0.0".
  - "Verwendungszweck:" merely restates the invoice number; it is not a
    structured payment reference, so reference_type/reference_value are
    always null. This is verified (the value must equal the invoice number),
    not just assumed.
  - business_id is "HRB <digits>" -- "Amtsgericht <city>" is context, dropped.
  - doc_id is derived from the pdf filename stem (not printed in the document).
  - Dates are DD.MM.YYYY -> ISO. Money is German-formatted (1.234,56) ->
    canonical "1234.56". Quantities are printed as plain digit strings with no
    thousands separator, even at 4 digits (e.g. "1227").

Fails loudly (ParserLayoutError) on any label, header, structure, or
arithmetic mismatch with what was induced above -- the hard boundaries
this parser was written against. No fallback/guessing behaviour.
"""

from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
import re

import pdfplumber


class ParserLayoutError(Exception):
    """Raised when the PDF does not match the layout this parser was induced from."""


# ---------------------------------------------------------------------------
# Constants describing the induced layout
# ---------------------------------------------------------------------------

_HEADER_ROW = "BEZEICHNUNG MENGE EINHEIT EINZELPREIS UST % GESAMT"
_ITEM_UNIT = "ST"
_REVERSE_CHARGE_TEXT = "Steuerfreie innergemeinschaftliche Lieferung"
_KAEUFER_LABEL = "KÄUFER"
_BANK_LABEL = "Bankverbindung"

_COUNTRY_MAP = {"Deutschland": "DE", "Finnland": "FI"}
_CURRENCY_MAP = {"€": "EUR"}
_VAT_RATE_MAP = {"0": "0.0"}

_DE_AMOUNT_RE = re.compile(r"^\d{1,3}(?:\.\d{3})*,\d{2}$")
_INT_RE = re.compile(r"^\d+$")
_DDMMYYYY_RE = re.compile(r"^(\d{2})\.(\d{2})\.(\d{4})$")

_RECHNUNG_NR_RE = re.compile(r"^Rechnung-Nr\.\s+(\S+)$")
_STREET_DATE_RE = re.compile(r"^(.+?)\s+Rechnungsdatum\s+(\d{2}\.\d{2}\.\d{4})$")
_CITY_DATE_RE = re.compile(r"^(\d{5})\s+(.+?),\s+(\S+)\s+Leistungsdatum\s+(\d{2}\.\d{2}\.\d{4})$")
_HRB_RE = re.compile(r"^HRB\s+(\d+),\s+Amtsgericht\s+\S.*$")
_FAELLIG_RE = re.compile(r"^Fälligkeitsdatum\s+(\d{2}\.\d{2}\.\d{4})$")
_SUPPLIER_VAT_RE = re.compile(r"^USt-IdNr\.\s+(\S+)$")
_BESTELLNR_RE = re.compile(r"^Bestellnummer\s+(\S+)$")
_BUYER_CITY_RE = re.compile(r"^(\d{5})\s+(.+?),\s+(\S+)$")
_REGISTERNUMMER_RE = re.compile(r"^Registernummer:\s+(\S+)$")
_BUYER_VAT_RE = re.compile(r"^USt-IdNr\.:\s+(\S+)$")
_NETTO_RE = re.compile(r"^Netto\s+(\d{1,3}(?:\.\d{3})*,\d{2})\s+(\S+)$")
_UST_RE = re.compile(r"^Umsatzsteuer\s+(\d+)\s+%\s+(\d{1,3}(?:\.\d{3})*,\d{2})\s+(\S+)$")
_BRUTTO_RE = re.compile(r"^Brutto\s+(\d{1,3}(?:\.\d{3})*,\d{2})\s+(\S+)$")
_IBAN_BIC_RE = re.compile(r"^IBAN:\s+(\S+)\s+BIC:\s+(\S+)$")
_ZAHLUNGSBED_RE = re.compile(r"^Zahlungsbedingungen:\s+(.+)$")
_VERWENDUNGSZWECK_RE = re.compile(r"^Verwendungszweck:\s+(\S+)$")


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------

def _match(regex, line, label):
    m = regex.match(line)
    if not m:
        raise ParserLayoutError(f"expected {label}, got: {line!r}")
    return m


def _amount_to_canonical(token, context):
    if not _DE_AMOUNT_RE.match(token):
        raise ParserLayoutError(f"{context}: {token!r} is not a recognised German decimal amount")
    return token.replace(".", "").replace(",", ".")


def _date_to_iso(token, context):
    m = _DDMMYYYY_RE.match(token)
    if not m:
        raise ParserLayoutError(f"{context}: {token!r} is not a DD.MM.YYYY date")
    day, month, year = (int(x) for x in m.groups())
    from datetime import date as _date

    try:
        d = _date(year, month, day)
    except ValueError as exc:
        raise ParserLayoutError(f"{context}: {token!r} is not a valid calendar date ({exc})")
    return d.isoformat()


def _country_to_iso(name, context):
    try:
        return _COUNTRY_MAP[name]
    except KeyError:
        raise ParserLayoutError(f"{context}: unrecognised country name {name!r}")


def _currency_to_iso(symbol, context):
    try:
        return _CURRENCY_MAP[symbol]
    except KeyError:
        raise ParserLayoutError(f"{context}: unrecognised currency symbol {symbol!r}")


def _rate_token_to_canonical(token, context):
    try:
        return _VAT_RATE_MAP[token]
    except KeyError:
        raise ParserLayoutError(f"{context}: unrecognised VAT rate token {token!r} for supplier s3")


def _parse_item_line(raw, line_no):
    tokens = raw.split()
    unit_positions = [i for i, t in enumerate(tokens) if t == _ITEM_UNIT]
    if len(unit_positions) != 1:
        raise ParserLayoutError(
            f"line {line_no}: expected exactly one {_ITEM_UNIT!r} unit token, "
            f"found {len(unit_positions)} in {raw!r}"
        )
    unit_idx = unit_positions[0]
    if unit_idx < 1:
        raise ParserLayoutError(f"line {line_no}: no quantity token before unit in {raw!r}")
    if len(tokens) != unit_idx + 4:
        raise ParserLayoutError(
            f"line {line_no}: expected <description...> <qty> ST <price> <vat%> <total>, "
            f"got {raw!r}"
        )

    description = " ".join(tokens[: unit_idx - 1])
    if not description:
        raise ParserLayoutError(f"line {line_no}: empty description in {raw!r}")

    quantity_tok = tokens[unit_idx - 1]
    if not _INT_RE.match(quantity_tok):
        raise ParserLayoutError(f"line {line_no}: quantity {quantity_tok!r} is not a plain integer")

    price_tok = tokens[unit_idx + 1]
    vat_tok = tokens[unit_idx + 2]
    total_tok = tokens[unit_idx + 3]

    unit_price = _amount_to_canonical(price_tok, f"line {line_no} unit price")
    vat_rate = _rate_token_to_canonical(vat_tok, f"line {line_no} VAT rate")
    line_total = _amount_to_canonical(total_tok, f"line {line_no} line total")

    expected_total = (Decimal(quantity_tok) * Decimal(unit_price)).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_UP
    )
    if expected_total != Decimal(line_total):
        raise ParserLayoutError(
            f"line {line_no}: {quantity_tok} x {unit_price} = {expected_total}, "
            f"printed line total is {line_total}"
        )

    return {
        "description": description,
        "quantity": quantity_tok,
        "unit": _ITEM_UNIT,
        "unit_price": unit_price,
        "vat_rate": vat_rate,
        "line_total": line_total,
    }



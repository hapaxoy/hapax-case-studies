if __name__ == "__main__":
    import json
    import sys

    args = sys.argv[1:]
    pairs = []

    if len(args) == 1 and args[0].lower().endswith(".json"):
        with open(args[0], "r", encoding="utf-8") as fh:
            manifest = json.load(fh)
        for item in manifest:
            pairs.append((item[0], item[1]))
    else:
        if len(args) == 0 or len(args) % 2 != 0:
            print(
                "Usage: parser_s3.py (pdf_path accepted_parse_json_path)... | manifest.json",
                file=sys.stderr,
            )
            sys.exit(2)
        for i in range(0, len(args), 2):
            pairs.append((args[i], args[i + 1]))

    failures = 0
    for pdf_path, json_path in pairs:
        with open(json_path, "r", encoding="utf-8") as fh:
            expected = json.load(fh)
        try:
            actual = parse(pdf_path)
        except ParserLayoutError as exc:
            print(f"FAIL {pdf_path}: ParserLayoutError: {exc}")
            failures += 1
            continue
        if actual == expected:
            print(f"PASS {pdf_path}")
        else:
            print(f"FAIL {pdf_path}: output mismatch")
            print(f"  expected: {expected}")
            print(f"  actual:   {actual}")
            failures += 1

    total = len(pairs)
    print(f"\n{total - failures}/{total} PASS")
    sys.exit(1 if failures else 0)

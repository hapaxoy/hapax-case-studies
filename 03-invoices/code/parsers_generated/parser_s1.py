if __name__ == "__main__":
    import json
    import sys

    def _load_pairs(argv):
        if len(argv) == 1 and argv[0].lower().endswith(".json"):
            with open(argv[0], "r", encoding="utf-8") as f:
                manifest = json.load(f)
            pairs = []
            for entry in manifest:
                if isinstance(entry, dict):
                    pairs.append((entry["pdf"], entry["json"]))
                else:
                    pairs.append((entry[0], entry[1]))
            return pairs
        if len(argv) % 2 != 0:
            print(
                "usage: parser_s1.py (<pdf_path> <accepted_parse_json>)... | <manifest.json>",
                file=sys.stderr,
            )
            sys.exit(2)
        return [(argv[i], argv[i + 1]) for i in range(0, len(argv), 2)]

    pairs = _load_pairs(sys.argv[1:])
    if not pairs:
        print(
            "usage: parser_s1.py (<pdf_path> <accepted_parse_json>)... | <manifest.json>",
            file=sys.stderr,
        )
        sys.exit(2)

    failures = 0
    for pdf_path, parse_json_path in pairs:
        doc_id = Path(pdf_path).stem
        try:
            got = parse(pdf_path)
        except ParserLayoutError as exc:
            failures += 1
            print(f"FAIL {doc_id}: ParserLayoutError: {exc}")
            continue

        with open(parse_json_path, "r", encoding="utf-8") as f:
            expected = json.load(f)

        if got == expected:
            print(f"PASS {doc_id}")
        else:
            failures += 1
            print(f"FAIL {doc_id}: parsed record does not match the accepted parse")
            for key in sorted(set(expected) | set(got)):
                if got.get(key) != expected.get(key):
                    print(f"  field {key!r} differs:")
                    print(f"    got:      {got.get(key)!r}")
                    print(f"    expected: {expected.get(key)!r}")

    total = len(pairs)
    print(f"\n{total - failures}/{total} PASS")
    sys.exit(1 if failures else 0)
